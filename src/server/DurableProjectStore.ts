import fs from 'node:fs';
import {validSprint,currentAttempt,type SprintState} from '../shared/sprint';
import path from 'node:path';
import {randomUUID} from 'node:crypto';
import type {ChatEntry, Session} from '../shared/protocol';
import {isLocale, validProjectWorkspace, type DurableProject, type Locale, type ProjectWorkspace} from '../shared/durable-project';
import {canonical, canonicalDirectory, privateDirectory, createRecord, replaceRecord, readRecord, sha256} from './runtime-coordinator/storage';
import {JournalLease} from './runtime-coordinator/JournalLease';
import {TransportError} from './transport';
import {redactSecrets} from './coach/context';

export interface SavedTrainingSession {
  lifecycle: Session['lifecycle']; timer: Session['timer']; activeFilePath: string | null;
}
interface State {
  sprint?: SprintState;
  schemaVersion: 1; projectId: string; locale: Locale; exercisePath: string | null;
  workspace: ProjectWorkspace; chat: ChatEntry[]; session: SavedTrainingSession | null;
  transitions: {path: string; at: string}[];
  rules: {text: string; sourceMessageId: string; at: string}[];
  notes: string[];
  observations: {kind: string; at: string; path: string | null; workspaceVersion: number | null}[];
  nativeSessions: Record<string, string>;
}
const MAX_BYTES = 8 * 1024 * 1024;
const uuid = (v: unknown): v is string => typeof v === 'string' && /^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$/i.test(v);
const fail = (code: string, message: string): never => {throw new TransportError(409, code, message);};
const copy = <T>(v: T): T => structuredClone(v);

/** One private, leased atomic JSON record; never copies or writes exercise source. */
export class DurableProjectStore {
  readonly desk: string;
  readonly directory: string;
  private readonly file: string;
  private readonly manifestBytes: Buffer;
  private lease: JournalLease;
  private digest: string;
  private state: State;
  private closed = false;
  private nativeBusy=new Set<string>();
  private constructor(readonly projectFile: string, private readonly manifest: {schemaVersion: 1; id: string; name: string}, create: boolean, locale: Locale) {
    this.directory = path.dirname(projectFile);
    canonicalDirectory(this.directory);
    this.manifestBytes = readRecord(projectFile, 16384)!;
    privateDirectory(path.join(this.directory, '.pairCoding'));
    this.desk = path.join(this.directory, '.pairCoding', 'codex');
    privateDirectory(this.desk);
    this.file = path.join(this.desk, 'state.json');
    this.lease = new JournalLease(path.join(this.desk, 'lease.lock'));
    try {
      const bytes = readRecord(this.file, MAX_BYTES, true);
      if (create) {
        if (bytes) fail('PROJECT_EXISTS', 'The directory already contains a training project.');
        this.state = {schemaVersion: 1, projectId: manifest.id, locale, exercisePath: null,
          workspace: {openTabs: [], activePath: null}, chat: [], session: null, transitions: [], rules: [], notes: [], observations: [], nativeSessions: {}};
        const encoded = this.encode(this.state);
        createRecord(this.file, encoded); this.digest = sha256(encoded);
        createRecord(path.join(this.desk, 'README.md'), Buffer.from('# PairCoding durable coach desk\n\nstate.json is the atomic platform-owned state: chat with original timestamps/locale, rules, notes, observations, exercise transitions and actual native session IDs. No private reasoning or credentials belong here.\n\nAdd a trusted project rule in chat with `/rule <text>` (or `Project rule: <text>` / `Zasada projektu: <text>`). Exercise files cannot authorize rule changes.\n\nresume.json contains exact session IDs, stable safe teacher working directories and shell-independent argv arrays (not executable shell text). Use codex --cd with that recorded directory even from another current directory; the copied AGENTS.md/skills persist across provider cleanup/backend restart. Native Codex account session files remain in the configured CODEX_HOME, never copied into this project. For an ID recorded in nativeSessions use `codex resume <ID>` interactively or `codex exec resume <ID> "your next instruction"`. Run with the SAME account/CODEX_HOME. No ID is generated by PairCoding. Do not use --ephemeral. A missing native session must be repaired explicitly, not replaced silently.\n\nThe selected character AGENTS.md and skills, locale, project rules, notes and restored chat are supplied again before each coach call. Notes are bounded operational summaries, not privileged instructions.\n'));
      } else {
        if (!bytes) fail('PROJECT_STATE_MISSING', 'Project state is missing; preserve the directory and restore its state.json.');
        this.state = JSON.parse(new TextDecoder('utf8', {fatal: true}).decode(bytes!));
        this.validate(this.state); this.digest = sha256(bytes!);
      }
    } catch (error) {this.lease.close(); throw error;}
  }
  static create(directory: string, name: string, locale: Locale = 'pl'): DurableProjectStore {
    if (typeof directory !== 'string' || !path.isAbsolute(directory) || directory.length > 4096 || /[\x00-\x1f]/.test(directory))
      fail('INVALID_PROJECT_PATH', 'Choose an absolute existing project directory.');
    const root = path.resolve(directory); canonicalDirectory(root);
    if(root.split(path.sep).some(p=>/^\.pair(?:coding|coach)$/i.test(p)))fail('PROTECTED_PROJECT_PATH','Project metadata is not a project location.');
    if (typeof name !== 'string' || !name.trim() || name.trim().length > 100 || /[\x00-\x1f<>:"/\\|?*]/.test(name) || /[. ]$/.test(name))
      fail('INVALID_PROJECT_NAME', 'Choose a project name of 1–100 characters without path separators.');
    // One project per directory: the fixed desk must never bind to a second manifest.
    if (fs.existsSync(path.join(root, '.pairCoding'))) fail('PROJECT_EXISTS', 'This directory already has .pairCoding; open its existing project instead.');
    const projectFile = path.join(root, name.trim() + '.paircoding.json');
    const manifest = {schemaVersion: 1 as const, id: randomUUID(), name: name.trim()};
    createRecord(projectFile, Buffer.from(JSON.stringify(manifest, null, 2) + '\n'));
    // Failed initialization is retained, never destructively retried over uncertain state.
    return new DurableProjectStore(projectFile, manifest, true, locale);
  }
  static open(projectFile: string): DurableProjectStore {
    if (typeof projectFile !== 'string' || !path.isAbsolute(projectFile) || projectFile.length > 4096 || !projectFile.endsWith('.paircoding.json'))
      fail('INVALID_PROJECT_FILE', 'Select an existing .paircoding.json project file.');
    const file = path.resolve(projectFile);
    let m:any;
    try {const bytes=readRecord(file,16384)!;m=JSON.parse(new TextDecoder('utf8',{fatal:true}).decode(bytes));}
    catch {throw new TransportError(400,'PROJECT_FILE_UNAVAILABLE','Cannot read the selected project file. Select a safe existing .paircoding.json file; the current project was preserved.');}
    if (!m || m.schemaVersion !== 1 || !uuid(m.id) || typeof m.name !== 'string' || !m.name.trim() || m.name.length > 100 ||
        Object.keys(m).some(k => !['schemaVersion', 'id', 'name'].includes(k))) fail('PROJECT_VERSION_UNSUPPORTED', 'Invalid or unsupported project format.');
    return new DurableProjectStore(file, m, false, 'pl');
  }
  private validate(s: State) {
    if (!s || s.schemaVersion !== 1 || s.projectId !== this.manifest.id || !isLocale(s.locale) || !validProjectWorkspace(s.workspace) ||
      !(s.exercisePath === null || typeof s.exercisePath === 'string' && path.isAbsolute(s.exercisePath)) ||
      !Array.isArray(s.chat) || s.chat.length > 10000 || s.chat.some(m => !m || !['STUDENT','COACH','SYSTEM'].includes(m.author) ||
        typeof m.messageId !== 'string' || typeof m.text !== 'string' || m.text.length > 12000 || !Number.isFinite(Date.parse(m.createdAt)) || (m.locale !== undefined && !isLocale(m.locale))) ||
      !Array.isArray(s.rules) || s.rules.length > 200 || s.rules.some(r => !r || typeof r.text !== 'string' || r.text.length > 2000 || typeof r.sourceMessageId !== 'string') ||
      !Array.isArray(s.notes) || s.notes.length > 100 || s.notes.some(n => typeof n !== 'string' || n.length > 2000) ||
      !Array.isArray(s.transitions) || s.transitions.length > 1000 || s.transitions.some(t => !t || typeof t.path !== 'string' || !path.isAbsolute(t.path) || !Number.isFinite(Date.parse(t.at))) ||
      !Array.isArray(s.observations) || s.observations.length > 1000 || s.observations.some(o => !o || typeof o.kind !== 'string' || !Number.isFinite(Date.parse(o.at))) ||
      !s.nativeSessions || typeof s.nativeSessions !== 'object' || Array.isArray(s.nativeSessions) || Object.keys(s.nativeSessions).length > 50 || Object.values(s.nativeSessions).some(v => !uuid(v)))
      fail('PROJECT_STATE_INVALID', 'Invalid project state; preserve state.json and repair it before opening.');
    if(s.sprint!==undefined && !validSprint(s.sprint))fail('PROJECT_SPRINT_INVALID','Invalid saved sprint; preserve state.json.');
    const saved = s.session;
    if (saved && (!['READY','RUNNING','FINISHED'].includes(saved.lifecycle) || !saved.timer || !Number.isSafeInteger(saved.timer.elapsedMs) || saved.timer.elapsedMs < 0 ||
      !(saved.timer.limitMs === null || Number.isSafeInteger(saved.timer.limitMs) && saved.timer.limitMs >= 1000 && saved.timer.limitMs <= 86400000) ||
      typeof saved.timer.pauseOnHidden !== 'boolean' || typeof saved.timer.manualPaused !== 'boolean' ||
      !(saved.activeFilePath === null || typeof saved.activeFilePath === 'string'))) fail('PROJECT_SESSION_INVALID', 'Invalid saved timer/session.');
  }
  private encode(s: State): Buffer {
    this.validate(s);
    const bytes = Buffer.from(JSON.stringify(s, null, 2) + '\n');
    if (bytes.length > MAX_BYTES) fail('PROJECT_STORAGE_LIMIT', 'Project history reached 8 MiB; export/archive the project before continuing. No history was discarded.');
    return bytes;
  }
  private assertCurrent() {
    if (this.closed) fail('PROJECT_CLOSED', 'Project is closed.');
    canonicalDirectory(this.directory); this.lease.assertCurrent();
    if (!readRecord(this.projectFile, 16384)!.equals(this.manifestBytes) || sha256(readRecord(this.file, MAX_BYTES)!) !== this.digest)
      fail('PROJECT_DISK_CONFLICT', 'Project metadata changed on disk; preserve it and reopen safely.');
  }
  update(change: (state: State) => void): void {
    this.assertCurrent(); const next = copy(this.state); change(next); const bytes = this.encode(next);
    if (canonical(next) === canonical(this.state)) return;
    // Existing record must remain a safe regular single-link file immediately before replacement.
    this.assertCurrent(); replaceRecord(this.file, bytes); this.digest = sha256(bytes!); this.state = next;
  }
  view(): DurableProject {return {id: this.manifest.id, name: this.manifest.name, directory: this.directory, projectFile: this.projectFile,
    exercisePath: this.state.exercisePath, workspace: copy(this.state.workspace), locale: this.state.locale, ...(this.state.sprint ? {sprint:copy(this.state.sprint)} : {})};}
  snapshot() {this.assertCurrent(); return copy(this.state);}
  setLocale(locale: Locale) {this.update(s => {s.locale = locale;});}
  setWorkspace(workspace: ProjectWorkspace) {if (!validProjectWorkspace(workspace)) fail('INVALID_PROJECT_WORKSPACE', 'Invalid tabs/active file.'); this.update(s => {s.workspace = copy(workspace);});}
  recordExercise(exercisePath: string) {this.update(s => {
    if (s.exercisePath === exercisePath) return;
    s.exercisePath = exercisePath; s.workspace = {openTabs: [], activePath: null}; s.session = null;
    s.transitions = [...s.transitions, {path: exercisePath, at: new Date().toISOString()}].slice(-1000);
  });}
  commitExercise(exercisePath:string,chat:ChatEntry[],session:Session,sprint?:SprintState):void {this.update(s=>{
    if(s.exercisePath!==exercisePath){s.exercisePath=exercisePath;s.workspace={openTabs:[],activePath:null};s.transitions=[...s.transitions,{path:exercisePath,at:new Date().toISOString()}].slice(-1000);}
    if(sprint)s.sprint=copy(sprint);
    else if(s.sprint?.status==='ACTIVE')s.sprint.status='SUSPENDED';
    s.chat=copy(chat);s.session={lifecycle:session.lifecycle,timer:copy(session.timer),activeFilePath:session.activeFilePath};
  });}
  capture(chat: ChatEntry[], session: Session | null, observations: State['observations'] = []) {this.update(s => {
    s.observations = [...s.observations,...copy(observations)].slice(-1000);
    s.chat = copy(chat);
    // Same atomic project capture; no second per-keystroke sprint write/pack scan.
    if(s.sprint?.status==='ACTIVE' && session && currentAttempt(s.sprint).sessionId===session.sessionId)
      s.sprint.elapsedMs=Math.max(s.sprint.elapsedMs,session.timer.elapsedMs);
    for(const message of chat) {
      if(message.author!=='STUDENT' || s.rules.some(r=>r.sourceMessageId===message.messageId))continue;
      const match=/^(?:\/rule\s+|Project rule:\s*|Zasada projektu:\s*)([^\r\n][\s\S]{0,1999})$/i.exec(message.text.trim());
      if(match)s.rules.push({text:redactSecrets(match[1]),sourceMessageId:message.messageId,at:message.createdAt});
    }
    if (session) s.session = {lifecycle: session.lifecycle, timer: copy(session.timer), activeFilePath: session.activeFilePath};
  });}
  observe(kind: string, path: string | null, workspaceVersion: number | null) {this.update(s => {
    s.observations = [...s.observations, {kind, path, workspaceVersion, at: new Date().toISOString()}].slice(-1000);
  });}
  remember(note: string) {if (note.trim()) this.update(s => {s.notes = [...s.notes, redactSecrets(note).slice(0, 2000)].slice(-100);});}
  nativeSession(key: string) {
    if (!/^[a-zA-Z0-9._:/-]{1,150}$/.test(key) || ['__proto__','constructor','prototype'].includes(key)) fail('INVALID_NATIVE_SCOPE', 'Invalid native session scope.');
    const directory=path.join(this.desk,'teacher-'+sha256(key).slice(0,24));
    privateDirectory(directory);
    return {
      directory,
      enter:()=>{this.assertCurrent();if(this.nativeBusy.has(key))fail('NATIVE_SESSION_BUSY','Previous native invocation is still settling. Retry after it has closed.');this.nativeBusy.add(key);},
      leave:()=>{this.nativeBusy.delete(key);},
      id: () => this.snapshot().nativeSessions[key],
      started: (id: string) => {
        if (!uuid(id)) fail('INVALID_NATIVE_SESSION', 'The CLI did not return a valid native session ID.');
        this.update(s => {
          if (s.nativeSessions[key] && s.nativeSessions[key] !== id) fail('NATIVE_SESSION_CHANGED', 'Native resume returned another session; refusing silent replacement.');
          s.nativeSessions[key] = id;
        });
        const resumeFile=path.join(this.desk,'resume.json');
        const bytes=Buffer.from(JSON.stringify({schemaVersion:1,sessions:Object.entries(this.state.nativeSessions).map(([scope,threadId])=>({scope,threadId,
          cwd:path.join(this.desk,'teacher-'+sha256(scope).slice(0,24)),
          interactiveArgv:['codex','--cd',path.join(this.desk,'teacher-'+sha256(scope).slice(0,24)),'resume',threadId],
          nonInteractiveArgv:['codex','--cd',path.join(this.desk,'teacher-'+sha256(scope).slice(0,24)),'exec','resume',threadId,'YOUR NEXT INSTRUCTION']}))},null,2)+'\n');
        if(readRecord(resumeFile,65536,true))replaceRecord(resumeFile,bytes);else createRecord(resumeFile,bytes);
      },
      remember: (note: string) => this.remember(note),
    };
  }
  coachContext() {const s = this.snapshot(); return {projectId: this.manifest.id, rules: s.rules.map(r => r.text), notes: s.notes.slice(-20),
    transitions: s.transitions.slice(-20), observations: s.observations.slice(-30)};}
  close() {if (!this.closed) {this.closed = true; this.lease.close();}}
}
