/** User-facing error is localized; original codes/details remain diagnostic, not translated as exercise content. */
export function problemText(message:string|null|undefined):string {
  if(!message)return '';
  if(Object.hasOwn(uiMessages,message)||reverseMessages.has(message))return t(message);
  const localized=localizeDiagnostic(message,locale);
  if(localized!==message)return /^[A-Z][A-Z0-9_]+:/.test(message)?localized+' ['+message+']':localized;
  const code=message.match(/\b[A-Z][A-Z_]{3,}\b/g)?.find(code=>Object.hasOwn(problemLabels,code));
  return (code?t(problemLabels[code]):t('Operacja nie powiodła się. Szczegóły diagnostyczne:'))+' '+message;
}

