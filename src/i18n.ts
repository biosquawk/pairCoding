const listeners=new Set<()=>void>();
export const getUiLocale=()=>locale;
export function setUiLocale(next:UiLocale) {
  if(next!=='pl'&&next!=='en')throw new Error('Invalid locale');
  locale=next;
  if(typeof document!=='undefined')document.documentElement.lang=next;
  try { if(typeof window!=='undefined')window.localStorage.setItem('paircoach:locale',next); } catch { /* Keep toggle usable. */ }
  for(const listener of listeners)listener();
}
export function useLocale():UiLocale {
  return useSyncExternalStore(cb=>{listeners.add(cb);return()=>{listeners.delete(cb);};},getUiLocale,()=> 'pl' as UiLocale);
}
const reverseMessages = new Map(Object.entries(uiMessages).map(([pl,en])=>[en,pl]));
export function t(text:string, values:Record<string,unknown>={}, selected:UiLocale=locale):string {
  const key=Object.hasOwn(uiMessages,text)?text:(reverseMessages.get(text)??text);
  const translated=selected==='en'?(uiMessages[key]??text):key;
  return translated.replace(/\{(\d+)\}/g,(key,index)=>Object.hasOwn(values,index)?String(values[index]):key);
}
